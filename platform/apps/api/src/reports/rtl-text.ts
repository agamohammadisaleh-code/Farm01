/**
 * موتور رسم متن فارسی در PDF.
 *
 * چرا این‌قدر دستی؟ چون pdfkit دو کار را خودش انجام می‌دهد و دو کار را نه:
 *  - شکل‌دهی حروف عربی/فارسی (چسبیدن اول/میان/آخر) را انجام می‌دهد، پس نباید
 *    حروف را دوباره به شکل چسبیده تبدیل کنیم؛ وگرنه متن دوبار تبدیل و خراب
 *    می‌شود.
 *  - ترتیب دوجهته را درست انجام نمی‌دهد: هر واژه را جدا می‌چیند و واژه‌ها را
 *    به ترتیب چپ‌به‌راست روی خط می‌گذارد، در نتیجه «سلام دنیا» به شکل
 *    «دنیا سلام» دیده می‌شود.
 *
 * راه‌حل: واژه‌ها را خودمان محاسبه و از راست به چپ رسم می‌کنیم. pdfkit هر
 * واژه را جدا می‌چیند، پس کافی است جای هر واژه را بدهیم؛ شکل‌دهی حروف را هم
 * به خودش می‌سپاریم.
 *
 * استثنا: نشانه‌های خنثی چسبیده به عدد (٪ و ٪) باید واژه جدا باشند، وگرنه
 * fontkit کل قطعه را معکوس می‌کند و «۹۲٫۹۷٪» به «٪۷۹٫۲۹» تبدیل می‌شود.
 */

/** نشانه‌هایی که باید مستقل از عدد چیده شوند */
const DETACHABLE = /([0-9۰-۹.,٬٫]+)\s*(٪|%)/g;

/**
 * ارقام فارسی → لاتین، فقط برای PDF.
 *
 * fontkit ارقام فارسی (`U+06F0..U+06F9`) را بخشی از متن راست‌به‌چپ می‌بیند و
 * هر قطعه عددی را معکوس می‌چیند؛ نتیجه «۹۲٫۹۷» به شکل «۷۹٫۲۹» درمی‌آید.
 * ارقام لاتین با جهت چپ‌به‌راست درست چیده می‌شوند، پس در PDF از همان‌ها
 * استفاده می‌کنیم (در Excel، JSON و رابط وب، ارقام فارسی می‌مانند).
 */
export function latinDigits(text: string): string {
  return text
    .replace(/[۰-۹]/g, (d) => String(d.charCodeAt(0) - 0x06f0))
    .replace(/[٠-٩]/g, (d) => String(d.charCodeAt(0) - 0x0660))
    .replace(/٬/g, ",")
    .replace(/٫/g, ".")
    .replace(/؛/g, ";");
}

/**
 * پرانتز و قلاب را واژه جدا می‌کنیم و آینه می‌کنیم.
 *
 * چون هر واژه چپ‌به‌راست رسم می‌شود ولی جمله از راست چیده می‌شود، پرانتز بازِ
 * چسبیده به واژه در سمت چپش می‌نشیند و «)گرم(» دیده می‌شود. جداکردن و
 * جابه‌جایی، ترتیب درست «(گرم)» را برمی‌گرداند.
 */
const BRACKET_MIRROR: Record<string, string> = { "(": ")", ")": "(", "[": "]", "]": "[" };
const BRACKETS = /[()\[\]]/g;

/** شکستن متن به واژه‌های قابل رسم */
export function tokenize(text: string): string[] {
  const normalized = latinDigits(text)
    .replace(DETACHABLE, "$1 $2")
    .replace(BRACKETS, " $& ")
    .replace(/[·|—–]/g, " $& ");
  return normalized
    .split(/\s+/)
    .filter((t) => t.length > 0)
    .map((t) => BRACKET_MIRROR[t] ?? t);
}
